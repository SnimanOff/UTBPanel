// Command gen regenerates code from openapi.yaml (make gen):
//
//   - backend/api/operations_gen.go — the operation table with MCP levels;
//   - frontend/src/lib/api/schema.d.ts — TypeScript types (openapi-typescript).
//
// Both files carry the SHA-256 of the spec; a test fails when the spec
// changed and gen was not run.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	spec "github.com/SnimanOff/UTBPanel/backend/api"
)

func main() {
	sum := sha256.Sum256(spec.YAML)
	hash := hex.EncodeToString(sum[:])
	ops, err := spec.Operations()
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by api/gen from openapi.yaml. DO NOT EDIT.\n\npackage spec\n\n")
	fmt.Fprintf(&b, "// GeneratedHash is the SHA-256 of openapi.yaml this file was made from.\nconst GeneratedHash = %q\n\n", hash)
	fmt.Fprintf(&b, "// Op is one operation of the API.\ntype Op struct {\n\tID, Method, Path, MCP, Summary string\n}\n\n")
	fmt.Fprintf(&b, "// Ops lists all operations.\nvar Ops = []Op{\n")
	for _, op := range ops {
		fmt.Fprintf(&b, "\t{%q, %q, %q, %q, %q},\n", op.ID, op.Method, op.Path, op.MCP, op.Summary)
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("operations_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}

	ts := filepath.Join("..", "..", "frontend", "src", "lib", "api", "schema.d.ts")
	cmd := exec.Command("npx", "-y", "openapi-typescript@7", "openapi.yaml", "-o", ts)
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("openapi-typescript: %v", err)
	}
	out, err := os.ReadFile(ts)
	if err != nil {
		log.Fatal(err)
	}
	stamp := "// spec sha256: " + hash + "\n"
	if !strings.HasPrefix(string(out), "// spec sha256: ") {
		out = append([]byte(stamp), out...)
	}
	if err := os.WriteFile(ts, out, 0o644); err != nil {
		log.Fatal(err)
	}
}
